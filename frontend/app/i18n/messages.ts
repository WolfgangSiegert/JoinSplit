const messages: Record<AppLocale, Record<MessageKey, string>> = { de, en }

export function translate(locale: AppLocale, key: MessageKey, params: Readonly<Record<string, string | number>> = {}): string {
  const template = messages[locale][key] ?? messages.en[key]
  return template.replace(/\{(\w+)\}/gu, (_match, name: string) => String(params[name] ?? `{${name}}`))
}

